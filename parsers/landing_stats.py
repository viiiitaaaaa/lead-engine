"""Все цифры основы лендинга (docs/лендинг_основа.md) из исходных данных — чтобы любую можно было перепроверить.
Создан 03.10 при перепроверке: раньше в «подрядчиков» попадали карточки посёлков, офисы продаж, ателье и АЗС, а 714 «жалоб» были упоминаниями болей.

python parsers/landing_stats.py
"""
import glob
import json
import re

import pandas as pd

from yandex_maps_bd import DRIVE, ROOT

# подрядчики и поставщики: стройка, отделка, инженерия, вода, мебель, сантехника, дизайн, архитектура
RELEVANT = (r"строит|құрылыс|ремонт|отделк|өңдеу|коттедж және саяжай|дачн\w* дом|инженер|котл|котел|котёл|отоплен|водоочист|водоснаб|фильтр\w* для воды"
            r"|септик|канализ|вентиляц|кондицион|климат|мебел|сантехник|плитк|потолоч|кирпич|дизайн|архитект|сәулет|проектир|окна|двер|кровл|фасад|электромонтаж")
NOT_OURS = r"коттедж\w* посёл|коттедж қалашығы|офис продаж|недвижимост|жылжымайтын|агентств|гольф|коммунал|^база|ателье|азс|автосервис|провайдер|турфирм"
NO_THEME = {"Коммуникации посёлка (газ, свет, дороги, вода)", "Управляющая компания и платежи", "Не по теме", "nan", ""}
PRAISE = {
    "Качество, аккуратность": r"качеств|аккуратн",
    "Конкретный прораб / менеджер": r"прораб|менеджер|руководител\w* проект|бригадир",
    "«Рекомендую»": r"рекомендую|рекомендуем",
    "Пришли по совету знакомых": r"по рекомендаци|посоветовал|по совету|знакомы[ехм] посоветов|друзья посоветов",
    "Сроки": r"в срок|вовремя|сроки соблюд|раньше срока|точно в срок",
    "Дизайн, проект": r"дизайн|визуализ|планировк",
    "Материалы, поставки": r"материал|поставк|оригинал",
    "Всегда на связи": r"на связи|всегда отвеча|оперативн\w* (отвеч|реаг)",
    "Смета не выросла": r"смет\w* (не (менял|вырос|увелич))|без доплат|ничего не доплачив|цена не (менял|вырос)|как договорились",
    "Под ключ, одна компания": r"под ключ|от и до|одна компания|комплектац",
    "Контроль удалённо (живут не рядом)": r"за границ|другой стран|удал[её]нно|за пределами|онлайн[- ]контрол|видеоотч",
}


def reviews() -> pd.DataFrame:
    """отзывы о подрядчиках и поставщиках: Яндекс Карты (без посёлков и посторонних) + 2ГИС групп «бюро» и «подрядчики»"""
    rev = pd.read_excel(sorted(glob.glob(str(DRIVE / "яндекс_отзывы_*.xlsx")))[-1], sheet_name="отзывы")
    kind = rev["вид деятельности"].astype(str)
    y = rev[(rev["тип запроса"] != "посёлок") & kind.str.contains(RELEVANT, case=False, regex=True)
            & ~kind.str.contains(NOT_OURS, case=False, regex=True)]
    rows = [{"оценка": pd.to_numeric(r["оценка"], errors="coerce"), "текст": str(r["отзыв"]), "откуда": "Яндекс"} for _, r in y.iterrows()]
    for g in ("premium", "contractors"):
        for v in json.loads((ROOT / f"data/raw/gis_reviews_{g}.json").read_text(encoding="utf-8")).values():
            rows += [{"оценка": x.get("оценка"), "текст": str(x.get("текст", "")), "откуда": "2ГИС"} for x in v["отзывы"]]
    d = pd.DataFrame(rows).dropna(subset=["оценка"])
    return d.drop_duplicates("текст")


def main():
    d = reviews()
    pos, neg = d[d["оценка"] >= 4], d[d["оценка"] <= 3]
    print(f"ОТЗЫВЫ о подрядчиках и поставщиках: {len(d)} (Яндекс {sum(d['откуда'] == 'Яндекс')}, 2ГИС {sum(d['откуда'] == '2ГИС')}); "
          f"положительных {len(pos)}, отрицательных {len(neg)}")
    print("\nПОХВАЛЫ — доля положительных отзывов, где упомянуто:")
    for k, rx in PRAISE.items():
        n = pos["текст"].str.contains(rx, case=False, regex=True).sum()
        print(f"  {k:40} {n:5}  {n * 100 / len(pos):4.1f}%")

    c = pd.read_excel(DRIVE / "карта_болей_2026-09-30.xlsx", sheet_name="жалобы")
    k = c["вид деятельности"].astype(str)
    cc = c[(c["тип запроса"] != "посёлок") & ~k.str.contains(NOT_OURS, case=False, regex=True)]
    th = cc["темы (по-русски)"].astype(str).str.split("; ").explode()
    th = th[~th.isin(NO_THEME)]
    vc = th.value_counts()
    print(f"\nЖАЛОБЫ на подрядчиков и поставщиков: {len(cc)} отзывов, {cc['организация'].nunique()} организаций, упоминаний болей {vc.sum()}")
    for t, n in vc.items():
        print(f"  {t:58} {n:4}  доля упоминаний {n * 100 / vc.sum():5.1f}%   в {n * 100 / len(cc):3.0f}% жалоб")
    top4 = vc.iloc[:4].sum() * 100 / vc.sum()
    print(f"  первые четыре: {top4:.1f}%")

    v = c[c["тип запроса"] == "посёлок"]
    tv = v["темы (по-русски)"].astype(str).str.split("; ").explode()
    print(f"\nЖАЛОБЫ на посёлки: {len(v)} отзывов")
    print(tv[~tv.isin({'nan', '', 'Не по теме'})].value_counts().to_string())


if __name__ == "__main__":
    main()

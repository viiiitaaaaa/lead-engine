    neg = [x["текст"] for x in rv if x.get("оценка") and x["оценка"] <= 3 and x.get("текст")]
    pos = [x["текст"] for x in rv if x.get("оценка") and x["оценка"] >= 4 and x.get("текст")]
    res["монтажники"] = {"компаний": len(inst), "отзывов": len(rv), "негатив": len(neg), "позитив": len(pos),
                         "боли": count(neg, THEMES), "похвалы": count(pos, PRAISE)}
    br = json.loads((ROOT / "data/raw/klimat_brendy.json").read_text(encoding="utf-8"))
    bneg = [x["текст"] for v in br.values() for x in v["отзывы"] if x.get("оценка") and x["оценка"] <= 3 and x.get("текст")]
    res["бренды"] = {"отзывов": sum(len(v["отзывы"]) for v in br.values()), "негатив": len(bneg),
                     "по брендам": {b: len(v["отзывы"]) for b, v in br.items() if v["отзывы"]}, "боли": count(bneg, THEMES)}
    ff = ROOT / "data/raw/klimat_forumy.json"
    if ff.exists():
        fo = json.loads(ff.read_text(encoding="utf-8"))
        posts = [p for t in fo.values() for p in t.get("посты", [])]
        prob = [p for p in posts if any(re.search(rx, p, re.I) for rx in FORUM_THEMES.values())]
        b = count(prob, FORUM_THEMES)
        for k, rx in FORUM_THEMES.items():  # цитаты — только фразы от первого лица о проблеме
            b[k]["цитаты"] = sorted({s for p in prob for s in sentences(p) if re.search(rx, s, re.I) and re.search(ME, s, re.I) and len(s) <= 220}, key=len)[:3]
        res["форумы"] = {"тем": len(fo), "сообщений": len(posts), "с проблемой": len(prob), "боли": b,
                         "по форумам": {f: sum(1 for t in fo.values() if t["форум"] == f) for f in {t["форум"] for t in fo.values()}}}
        fh = ROOT / "data/raw/klimat_forumhouse_svod.json"  # ForumHouse: посчитано в Chrome теми же правилами
        if fh.exists():
            h = json.loads(fh.read_text(encoding="utf-8"))
            f = res["форумы"]
            f["тем"] += h["тем"]; f["сообщений"] += h["сообщений"]; f["с проблемой"] += h["с проблемой"]; f["по форумам"]["forumhouse.ru"] = h["тем"]
            for k, v in h["боли"].items():
                f["боли"][k]["сколько"] += v["сколько"]
                f["боли"][k]["цитаты"] = (v["цитаты"] + f["боли"][k]["цитаты"])[:3]
    if ff.exists():  # сантехника: форумы (Мастерград, АВОК; ForumHouse этой темой не проверяли) + негатив 2ГИС всех групп
        fpost = [p for p in posts if re.search(SANTEH, p, re.I)]
        gneg = []
        for g in (ROOT / "data/raw").glob("gis_reviews*.json"):
            d = json.loads(g.read_text(encoding="utf-8"))
            for c in (d.values() if isinstance(d, dict) else d):
                for x in (c.get("отзывы") if isinstance(c, dict) else c) or []:
                    if isinstance(x, dict) and x.get("оценка") and x["оценка"] <= 3 and x.get("текст"):
                        gneg.append(x["текст"])
        gneg = list(set(gneg))
        res["сантехника"] = {"форум": len(fpost), "форум_всего": len(posts), "отзывы": sum(1 for t in gneg if re.search(SANTEH, t, re.I)),
                             "отзывы_всего": len(gneg),
                             "цитаты": sorted({s for p in fpost for s in sentences(p) if re.search(SANTEH, s, re.I) and len(s) <= 220}, key=len)}
    (ROOT / "data/raw/klimat_boli.json").write_text(json.dumps(res, ensure_ascii=False), encoding="utf-8")

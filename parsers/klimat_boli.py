def sentences(t: str) -> list:
    return [s.strip() for s in re.split(r"(?<=[.!?…\n])\s+", t or "") if 15 <= len(s.strip()) <= 400]


def count(texts: list, themes: dict) -> dict:
    out = {}
    for k, rx in themes.items():
        hits = [(t, next((s for s in sentences(t) if re.search(rx, s, re.I)), "")) for t in texts if re.search(rx, t or "", re.I)]
        out[k] = {"сколько": len(hits), "цитаты": sorted({s for _, s in hits if s}, key=len)[:4]}
    return out



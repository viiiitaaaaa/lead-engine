def main():
    d = json.loads((ROOT / "data/raw/wordstat_premium.json").read_text(encoding="utf-8"))
    md = ("## 11а. Премиум-сегменты — что ищет очень богатый клиент\n"
          "Наш клиент — очень богатый человек или его жена; мы делаем архитектуру, дизайн, стройку и всю инженерию, только премиум-люкс (её слова 04.10). "
          "Ниже — сколько раз в месяц ищут в Яндексе по Москве и области (Вордстат, все устройства) её запросы и запросы соседних премиальных тем.\n\n"
          "| Тема | Запрос | В месяц | Самые частые запросы | Пометка |\n|---|---|---|---|---|\n")
    for g, q, n, top, note in d["rows"]:
        md += f"| {g} | {q} | **{n:,}** | {top} | {note} |\n".replace(",", " ")
    md += ("\n**Вывод.** Богатый клиент сам почти ничего не ищет: «климат в частном доме» — 7 запросов в месяц, «кинотеатр в частном доме» — 20, "
           "«хамам в частном доме» — 118, «винная комната» — 251, «кинотеатр на яхте» — 0. Большие числа — массовый спрос: «умный дом» — это Алиса, "
           "«домашний кинотеатр» — колонки и проекторы, «баня в доме» и «бассейн в доме» — аренда на выходные. "
           "Значит, **реклама в поиске на этого клиента не работает**: за него ищут и решают архитекторы, дизайнеры, помощники и управляющие домом. "
           "Ключевые слова нужны для страниц сайта (по одной на сегмент — чтобы архитектор нашёл и переслал), а не ради трафика.\n\n"
           "**Какие премиум-сегменты можно ещё рассмотреть** (по логике её списка: всё, что в доме очень богатого человека требует точного климата, "
           "воды, тишины и одной ответственности за проект):\n\n"
           "| Сегмент | Что в нём наше | Спрос в поиске (в месяц) | Как выходить |\n|---|---|---|---|\n")
    for seg, ours, demand, how in SEGMENTS:
        md += f"| {seg} | {ours} | {demand} | {how} |\n"
    s = MD.read_text(encoding="utf-8")
    s = re.sub(r"\n*<!-- prem -->.*?<!-- /prem -->\n?", "\n", s, flags=re.S)
    block = f"<!-- prem -->\n{md}<!-- /prem -->\n"
    s = s.replace("<!-- /r11 -->\n", "<!-- /r11 -->\n\n" + block, 1) if "<!-- /r11 -->" in s else s.rstrip() + "\n\n" + block
    MD.write_text(s, encoding="utf-8")
    print("раздел 11а записан:", len(d["rows"]), "запросов,", len(SEGMENTS), "сегментов")


if __name__ == "__main__":
    main()

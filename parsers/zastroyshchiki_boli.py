"""Минусы в постройках застройщиков посёлков её списка — только то, что закрывает поставщик тех. оборудования (её задача 03.10:
«мне нужны отзывы о застройщиках этих посёлков — какие минусы в их постройках, чтобы понять, какие боли мы можем закрыть;
дорогу и лес мы не закроем»).
Источники: отзывы о застройщиках в 2ГИС (data/raw/zastroyshchiki_otzyvy_2gis.json) + отзывы о их проектах на Яндекс Картах
(проекты посёлков, VISION). Минус — фраза из отзыва с оценкой 1–3 или со словами о проблеме; только темы нашей зоны.

python parsers/zastroyshchiki_boli.py
Итог: data/raw/zastroyshchiki_boli.json → раздел 9 основы лендинга и панель.
"""
import glob
import json
import re

import pandas as pd

from yandex_maps_bd import DRIVE, ROOT

# застройщик → его проекты в посёлках её списка (по Циану и сводке посёлков; ссылки на карточки Яндекса — отзывы проектов)
DEV = {
    "Capital Group": {"посёлки": "Барвиха (Барвиха Хиллс)", "яндекс": ["240711631353"]},
    "Gletcher": {"посёлки": "Барвиха (Барвиха XXI), Ромашково (Ромашково XXI)", "яндекс": ["71161765177", "1392484079"]},
    "Снегири Девелопмент": {"посёлки": "Раздоры (Резиденция Рублёво)", "яндекс": ["227092145766"]},
    "Hals Development": {"посёлки": "Солослово (Берёзки River Village)", "яндекс": ["1418685493"]},
    "Lumi Polar": {"посёлки": "Солослово (Gorki Lake)", "яндекс": ["136987032194"]},
    "Villagio Estate": {"посёлки": "Виджион (VISION), Виладжио эстейт", "яндекс": ["210162961171", "228754231114"]},
    "Квинтурин": {"посёлки": "Жуковка (ParkVille)", "яндекс": ["113690077506"]},
    "Ландшафт": {"посёлки": "Жуковка (КП Ландшафт)", "яндекс": ["1297823533"]},
    "Жуковка 21 / Жуковка-2": {"посёлки": "Жуковка", "яндекс": ["27052057504", "131317798287"]},
    "Усадьбы Усово": {"посёлки": "Усово", "яндекс": ["32109573320"]},
}
OURS = {  # боли, которые закрывает поставщик технического оборудования
    "качество строительства": r"трещин|протек|протеч|теч[её]т|брак|некачествен|качество (строит|домов|работ)|переделыв|кровл|крыш|фасад|сырост|плесен|продува|промерза|косяк",
    "отопление и котлы": r"отоплен|кот[её]л|котл|котельн|т[её]пл\w* пол|радиатор|батаре|холодно в доме|замерза",
    "вода и канализация": r"нет (горячей )?воды|напор|водоснаб|водопровод|скважин|септик|канализ|засор|водоподгот|очистн|дренаж|подтоп|затоп",
    "вентиляция и климат": r"вентиляц|кондиционер|душн|влажн|конденсат|рекуперат|климат",
    "электричество": r"электрик|электричеств|проводк|свет (отключ|нет)|отключени\w* (свет|электр)|мощност|квт|генератор|щит",
    "газ и автономия": r"(?<![а-яё])газ|газифика|автоном",
    "отделка и сантехника": r"отделк|сантехник|окн[аоуе] (дует|продува|теку|кривы|не закрыва)|двер\w* (не закрыва|кривы)|плитк\w* (отвал|трес)|материал\w* (дешев|плох|некачеств)|дешев\w* материал|материал дешев",
    "гарантия и устранение дефектов": r"гаранти|дефект|устран|замечани|недоделк|после сдачи|приёмк|приемк",
}
NEG = (r"проблем|нет(?![а-яё])|не работа|плох|ужас|кошмар|отключ|не хватает|сломал|сломан|теч|брак|некачеств|переделыв|холодн|"
       r"дефект|недоделк|жалоб|минус|не греет|не держит|сыро|плесен|не устран|затопи|завышен|обман")


NOISE = r"шумощ|шумозащ|речушк|река протекает|протекает под|городского климата|т[её]плый дом|шумоза|квартир|номер[ау]? |апартамент"


def ya_reviews(cid: str, full: dict, rev: pd.DataFrame) -> list:
    fr = next((v for k, v in full.items() if f"/{cid}/" in k + "/"), None)
    if fr is not None:
        return [(x.get("оценка"), str(x.get("текст", ""))) for x in fr]
    return [(x["оценка"], str(x["отзыв"])) for _, x in rev[rev["id"] == cid].iterrows()]


def main():
    g2 = json.loads((ROOT / "data/raw/zastroyshchiki_otzyvy_2gis.json").read_text(encoding="utf-8"))
    full = json.loads((ROOT / "data/raw/yrev_full.json").read_text(encoding="utf-8"))
    rev = pd.read_excel(sorted(glob.glob(str(DRIVE / "яндекс_отзывы_*.xlsx")))[-1], sheet_name="отзывы")
    rev["id"] = rev["карточка"].astype(str).str.extract(r"/(\d{6,})/?$")[0]
    out, total = {}, {}
    for dev, meta in DEV.items():
        revs, seen_cards = [], set()
        for c in g2.get(dev, []):
            if c["id"] in seen_cards or re.search(r"апартамент|гостиниц|отел", c["name"], re.I):  # апарт-отель «ОКО» Capital Group — не дома
                continue
            if c["id"] in seen_cards:
                continue
            seen_cards.add(c["id"])
            revs += [(x.get("оценка"), x.get("текст", ""), f"2ГИС: {c['name']}") for x in c["отзывы"]]
        for cid in meta["яндекс"]:
            revs += [(r, t, "Яндекс Карты") for r, t in ya_reviews(cid, full, rev)]
        pains, seen = {}, set()
        for rating, txt, src in revs:
            rt = pd.to_numeric(rating, errors="coerce")
            for s in re.split(r"(?<=[.!?…\n])\s+", str(txt)):
                s = s.strip()
                if not 20 <= len(s) <= 320 or s in seen:
                    continue
                th = [t for t, rx in OURS.items() if re.search(rx, s, re.I)]
                if not th or not ((pd.notna(rt) and rt <= 3) or re.search(NEG, s, re.I)):
                    continue
                if re.search(NOISE, s, re.I):  # проверено глазами 03.10: природа, похвала, квартиры в ЖК, «шумозащитный»
                    continue
                if re.search(r"(?<![а-яё])нет (никаких )?(проблем|минусов|нареканий|замечаний)|без (проблем|нареканий)", s, re.I):
                    continue
                seen.add(s)
                for t in th[:2]:
                    pains.setdefault(t, []).append({"фраза": s, "оценка": None if pd.isna(rt) else int(rt), "источник": src})
                    total[t] = total.get(t, 0) + 1
        out[dev] = {"посёлки": meta["посёлки"], "отзывов разобрано": len(revs),
                    "боли": {t: {"сколько": len(v), "цитаты": sorted(v, key=lambda x: (x["оценка"] or 5, len(x["фраза"])))[:3]}
                             for t, v in sorted(pains.items(), key=lambda kv: -len(kv[1]))}}
        print(f"{dev:24} | отзывов {len(revs):4} | " + ", ".join(f"{t} {len(v)}" for t, v in sorted(pains.items(), key=lambda kv: -len(kv[1]))[:5]))
    out["_итого"] = dict(sorted(total.items(), key=lambda kv: -kv[1]))
    print("ИТОГО:", out["_итого"])
    (ROOT / "data/raw/zastroyshchiki_boli.json").write_text(json.dumps(out, ensure_ascii=False), encoding="utf-8")


if __name__ == "__main__":
    main()

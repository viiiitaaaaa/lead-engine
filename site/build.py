    import html as _h
    d = _h.unescape(kw["desc"])
    if len(d) > 160:
        cut = max(d.rfind(". ", 0, 160), d.rfind("! ", 0, 160), d.rfind("? ", 0, 160))
        d = d[:cut + 1] if cut > 60 else d[:157].rsplit(" ", 1)[0] + "…"
    kw["desc"] = escape(d)
    return HEAD.format(**kw)



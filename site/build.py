    if path not in _LQIP:
        import base64, io
        from PIL import Image, ImageFilter
        im = Image.open(SITE / path).convert("RGB")
        im = im.resize((24, max(1, round(im.height * 24 / im.width))), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1))
